// Cross-tool export and SKILLS.md index (pure builders; the hooks module writes them).

export const EXPORT_TARGETS: Record<string, { path: string; label: string }> = {
  cursor: { path: '.cursor/rules/skills.md', label: 'Cursor' },
  copilot: { path: '.github/copilot-instructions.md', label: 'GitHub Copilot' },
  windsurf: { path: '.windsurf/rules/skills.md', label: 'Windsurf' },
  cline: { path: '.clinerules/skills.md', label: 'Cline' },
}

export function buildExport(skills: { name: string; body: string }[]): string {
  const sections = skills.map(s => `## ${s.name}\n${s.body}`)
  return `# Skills (auto-generated by Skills Manager)\n\n${sections.join('\n\n---\n\n')}\n`
}

export type IndexEntry = { folder: string; name: string; description: string; category: string; enabled: boolean; userInvocable: boolean }

export function buildIndex(skills: IndexEntry[], skillsDir: string): string {
  const enabled = skills.filter(s => s.enabled)
  const grouped = new Map<string, IndexEntry[]>()
  for (const s of enabled) grouped.set(s.category, [...(grouped.get(s.category) ?? []), s])
  const lines = ['# Available Skills', '']
  for (const cat of [...grouped.keys()].sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()))) {
    lines.push(`## ${cat}`)
    for (const s of grouped.get(cat)!.sort((a, b) => a.name.localeCompare(b.name))) lines.push(`- ${s.name}: ${s.description}`)
    lines.push('')
  }
  lines.push(`Total: ${enabled.length} enabled skills`, '')
  const commands = enabled.filter(s => s.userInvocable).sort((a, b) => a.name.localeCompare(b.name))
  if (commands.length > 0) {
    lines.push('---', '', '## Slash Commands', '')
    lines.push('When the user invokes `/<skill-name>`, read the corresponding SKILL.md file for full instructions.', '')
    for (const c of commands) lines.push(`- \`/${c.name}\` → \`${skillsDir}/${c.folder}/SKILL.md\``)
    lines.push('')
  }
  return lines.join('\n')
}
